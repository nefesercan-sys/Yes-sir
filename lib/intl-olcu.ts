/** 10 dilli karşılıklı hreflang + x-default (TR). */
export function olcuLanguages(base: string): Record<string, string> {
  const m: Record<string, string> = Object.fromEntries(OLCU_ALL.map((l) => [OLCU_HREFLANG[l], `${base}${OLCU_PATH[l]}`]));
  m['x-default'] = `${base}${OLCU_PATH.tr}`;
  return m;
}

